"""Writes assets/ASSET_MANIFEST.md from the files actually present under assets/.

Every asset is mapped to the script that generates it and its licence/source. Run after
adding or regenerating assets:  python tools/gen_manifest.py
"""
import os
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
A = os.path.join(ROOT, "assets")

SOURCES = [
    ("ui/app_icon/", "tools/paint_app_icon.py", "Original - 2D procedural illustration"),
    ("ui/icons/", "tools/render_icons.tscn", "Original - rendered from the project's item models"),
    ("items/", "tools/blender/build_items.py", "Original - procedural Blender modelling"),
    ("environment/note", "tools/blender/build_items.py", "Original - procedural Blender modelling"),
    ("environment/elevator_car", "tools/blender/build_items.py", "Original - procedural Blender modelling"),
    ("characters/", "tools/blender/build_survivor.py", "Original - modelled, rigged and animated by script in Blender 5.2"),
    ("creatures/", "tools/blender/build_hunter.py", "Original creature design - modelled, rigged and animated by script"),
    ("props/devices/", "tools/blender/build_props.py", "Original - procedural Blender modelling"),
    ("props/", "tools/blender/build_props.py", "Original - procedural Blender modelling"),
    ("environment/", "tools/blender/build_props.py", "Original - procedural Blender modelling"),
    ("textures/", "tools/textures/gen_textures.py", "Original - NumPy procedural PBR synthesis"),
    ("effects/textures/flashlight_cookie", "tools/textures/gen_cookie.py", "Original - NumPy synthesis"),
    ("effects/", "tools/textures/gen_textures.py", "Original - NumPy synthesis"),
    ("../icon.png", "tools/paint_app_icon.py", "Original - 2D procedural illustration"),
    ("audio/", "tools/audio/gen_audio.py", "Original - NumPy offline synthesis (modal, FM, filtered noise, FFT reverb)"),
]


def source_for(rel):
    for prefix, script, lic in SOURCES:
        if rel.startswith(prefix):
            return script, lic
    return "hand-authored", "Original"


def main():
    groups = defaultdict(list)
    total = 0
    for dirpath, _dirs, files in os.walk(A):
        for f in sorted(files):
            if f.endswith((".import", ".uid", ".md")):
                continue
            full = os.path.join(dirpath, f)
            rel = os.path.relpath(full, A).replace(os.sep, "/")
            size = os.path.getsize(full)
            total += size
            groups[rel.split("/")[0]].append((rel, size))
    lines = [
        "# NIGHT SHIFT - Asset Manifest",
        "",
        "Generated by `tools/gen_manifest.py`. **Every asset in this project is original work created for",
        "NIGHT SHIFT** by the generator scripts listed below; no third-party, stock, marketplace or",
        "commercial assets are included. Re-running a generator reproduces its assets deterministically.",
        "",
        "Licence for all listed assets: project-owned (original work). No attribution obligations.",
        "",
        "Not bundled: UI text uses the device's system font through `SystemFont` (no font files shipped).",
        "",
        "| Category | Files | Size |",
        "|---|---:|---:|",
    ]
    for cat in sorted(groups):
        lines.append(f"| {cat} | {len(groups[cat])} | {sum(s for _, s in groups[cat]) / 1048576:.1f} MB |")
    lines += [f"| **total** | **{sum(len(v) for v in groups.values())}** | **{total / 1048576:.1f} MB** |", ""]
    for cat in sorted(groups):
        lines += [f"## {cat}", "", "| File | Generator | Source / licence |", "|---|---|---|"]
        for rel, _size in groups[cat]:
            script, lic = source_for(rel)
            lines.append(f"| `{rel}` | `{script}` | {lic} |")
        lines.append("")
    lines += [
        "## Remaining development placeholders",
        "",
        "These still use code-generated geometry and are scheduled for authored models:",
        "",
        "* Decal quads (blood smears, scattered papers) placed by `prop_factory.gd`.",
        "* Legacy fallbacks kept on purpose so the game still runs if an asset is missing:",
        "  `procedural_survivor_visual.gd`, `hunter_visual.gd`, `ProceduralAudio`, MeshKit prop builders.",
        "",
    ]
    with open(os.path.join(A, "ASSET_MANIFEST.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("manifest:", sum(len(v) for v in groups.values()), "files", f"{total / 1048576:.1f} MB")


if __name__ == "__main__":
    main()
